// @ts-check
// The concept × carrier matrix (src/concepts.js): for each concept, the questions that ask it on each
// carrier and the generic label rules. `npm run concepts` writes it to docs/concepts.md;
// test/concepts.test.mjs checks that file is current.

import { CONCEPTS } from '../../src/concepts.js';
import { CARRIERS } from '../../src/carriers.js';
import { GENERIC_RULES } from '../../src/rules.js';

/** @import { CarrierRule } from '../../types.js' */

// A question as the fill engine and the usage events name it: the carrier's question id, else its
// data-model field, selector or label pattern.
/** @param {CarrierRule} r */
export const questionId = (r) => r.q ?? r.field ?? r.selector ?? (r.label ? `/${r.label}/` : null) ?? (typeof r.ask === 'string' ? r.ask : r.name) ?? '?';

/** The rule sets the matrix covers: each carrier's, then the generic label rules. */
export const RULE_SETS = () => [
  ...CARRIERS.filter((c) => c.rules.length).map((c) => ({ id: c.id, name: c.name, rules: c.rules })),
  { id: 'generic', name: 'Generic label rules', rules: GENERIC_RULES },
];

/**
 * Each concept's questions per rule set, in catalog order.
 * @returns {{ id: string, meaning: string, asked: Record<string, string[]> }[]}
 */
export function conceptMatrix(sets = RULE_SETS()) {
  return Object.entries(CONCEPTS).map(([id, meaning]) => ({
    id,
    meaning,
    asked: Object.fromEntries(sets.map((s) => [s.id, [...new Set(s.rules.filter((r) => r.concept === id).map(questionId))]])),
  }));
}

const cell = (ids) => ids.map((x) => `\`${String(x).replace(/\|/g, '\\|').replace(/`/g, "'")}\``).join(', ');

/** docs/concepts.md: one table per subject. */
export function conceptMarkdown(sets = RULE_SETS()) {
  const rows = conceptMatrix(sets);
  const L = [
    '# Concepts: what each carrier question is about',
    '',
    'Generated by `npm run concepts` from [src/concepts.js](../src/concepts.js) and every carrier rule\'s `concept`; do not edit by hand. Each row is a concept and where it is asked: the carrier\'s question id (Progressive\'s `q`), else its data-model field, selector or label pattern, as the usage events name it. An empty cell: that carrier doesn\'t ask it. A change to a concept\'s answer touches every rule in its row; a new carrier question takes an existing concept when it means the same thing, else a new one in the catalog ([New carriers](new-carrier.md)).',
    '',
    `${rows.length} concepts, ${sets.map((s) => `${s.rules.length} ${s.id === 'generic' ? 'generic label rules' : `${s.name} rules`}`).join(', ')}.`,
  ];
  let subject = null;
  for (const row of rows) {
    const here = row.id.split('.')[0];
    if (here !== subject) {
      subject = here;
      L.push('', `## ${subject}`, '', `| Concept | Meaning | ${sets.map((s) => s.name).join(' | ')} |`, `| --- | --- | ${sets.map(() => '---').join(' | ')} |`);
    }
    L.push(`| \`${row.id}\` | ${row.meaning.replace(/\|/g, '\\|')} | ${sets.map((s) => cell(row.asked[s.id])).join(' | ')} |`);
  }
  return `${L.join('\n')}\n`;
}
